/*=====================================================
  GPIR RELATIONSHIPS INDEX GENERATOR

  Scans every structured content object under assets/data/content/**
  (excluding the schema/ and this generator's own output) and produces
  assets/data/content/relationships-index.json -- for every object, its
  own outbound `relationships` edges plus the *inbound* edges computed
  by scanning every other object.

  This file is generated, never hand-edited -- the same "generator is
  the source of truth" rule scripts/generate-intelligence-pages.js
  already established (see docs/CONTRIBUTING.md). Its purpose is to make
  content-object reuse across multiple contexts checkable rather than
  asserted: an object referenced from several different objects' edges
  shows up with several entries in its own `inboundRelationships` list,
  proof it wasn't copied per context.

  Run manually after adding/editing a content object's relationships:
    node scripts/generate-relationships-index.js

  Dev-time build step, like gpir-perf-audit.js and generate-intelligence-
  pages.js -- not a runtime dependency of any live page.
======================================================*/

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const CONTENT_DIR = path.join(ROOT, "assets/data/content");
const OUTPUT_PATH = path.join(CONTENT_DIR, "relationships-index.json");

function walkJsonFiles(dir, out = []){
    if(!fs.existsSync(dir)) return out;
    for(const entry of fs.readdirSync(dir, { withFileTypes: true })){
        if(entry.name === "schema") continue; // JSON Schema, not a content object
        const full = path.join(dir, entry.name);
        if(entry.isDirectory()) walkJsonFiles(full, out);
        else if(entry.name.endsWith(".json") && entry.name !== "relationships-index.json") out.push(full);
    }
    return out;
}

function main(){

    const files = walkJsonFiles(CONTENT_DIR);
    const objects = files.map(f => JSON.parse(fs.readFileSync(f, "utf8")));

    const byId = {};
    objects.forEach(obj => { byId[obj.id] = obj; });

    const index = {};
    objects.forEach(obj => {
        index[obj.id] = {
            title: obj.title,
            contentType: obj.contentType,
            outboundRelationships: obj.relationships || [],
            inboundRelationships: [],
        };
    });

    let unresolvedTargets = [];

    objects.forEach(obj => {
        (obj.relationships || []).forEach(edge => {
            if(!byId[edge.targetId]){
                unresolvedTargets.push(`${obj.id} -[${edge.type}]-> ${edge.targetId} (target not found)`);
                return;
            }
            index[edge.targetId].inboundRelationships.push({
                type: edge.type,
                sourceId: obj.id,
                sourceType: obj.contentType,
            });
        });
    });

    fs.writeFileSync(OUTPUT_PATH, JSON.stringify({
        generatedNote: "Generated by scripts/generate-relationships-index.js -- do not hand-edit. Re-run after changing any content object's relationships array.",
        objectCount: objects.length,
        index,
    }, null, 2));

    console.log(`Indexed ${objects.length} content object(s) from ${files.length} file(s).`);
    console.log(`Written ${path.relative(ROOT, OUTPUT_PATH)}`);

    if(unresolvedTargets.length){
        console.log(`\n${unresolvedTargets.length} unresolved relationship target(s):`);
        unresolvedTargets.forEach(t => console.log("  " + t));
    }

    // Reusability proof: which objects are referenced from more than one
    // other object -- i.e. genuinely reused across contexts rather than
    // duplicated per context, the point of this whole exercise.
    const reused = Object.entries(index).filter(([id, v]) => v.inboundRelationships.length > 1);
    console.log(`\n${reused.length} object(s) referenced from more than one other object (reused, not duplicated):`);
    reused.forEach(([id, v]) => {
        console.log(`  ${id} <- ${v.inboundRelationships.map(r => r.sourceId).join(", ")}`);
    });
}

main();
